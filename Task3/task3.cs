/*
1) CellCoordinate
Описание: АТД, инкапсулирующий концепцию 2D-координаты на дискретной сетке (строка, столбец). Гарантирует свою валидность (нахождение в пределах поля) и отвечает 
на вопрос о смежности (является ли соседним для другой координаты).
2) Gem (заменил Token)
Описание: Базовый АТД игрового элемента. Инкапсулирует свой тип/цвет и отвечает на вопрос о своей идентичности (может ли он образовать линию с другим Gem).
3) BonusGem (Наследник Gem)
Описание: Расширение базового кристалла. Моделирует особые состояния (бомба, уничтожитель ряда). Инкапсулирует паттерн своего разрушительного воздействия на 
окружающее пространство сетки.
4) GridBoard
Описание: Пространственная абстракция доски 8x8. Контейнер, обеспечивающий топологию: знает, какой Gem лежит по какой CellCoordinate, и умеет атомарно менять их местами.
Ограничен только физикой перемещения.
5) PatternMatcher
Описание: Математическая абстракция "правил игры". Анализирует GridBoard на предмет геометрических паттернов (линий из 3+ одинаковых Gem). Является "чистой" 
функцией-наблюдателем: не меняет доску, а возвращает списки координат, подлежащих уничтожению.
6) GravityEngine
Описание: АТД физического закона падения. Принимает GridBoard с пустыми ячейками и вычисляет новые конечные координаты для висящих в воздухе Gem. 
Управляет процессом заполнения пустот новыми элементами с неба.
7) PlayerMove
Описание: Абстракция пользовательского намерения. Инкапсулирует две CellCoordinate. Моделирует атомарную транзакцию (попытку обмена). Отвечает за логику отката 
(rollback), если обмен оказался нелегальным по правилам PatternMatcher.
8) ScoreSession
Описание: Бизнес-сущность, представляющая текущий прогресс игрока. Накапливает очки, применяет множители комбо за каскадные совпадения и хранит историю 
результативности.

*/
