/*
1. Token
Объект, представляющий конкретный символ на доске (например, 'A', 'B', 'C') и его текущий статус, хранит информацию о том, является ли он обычным элементом или содержит бонус.
2. Grid
Абстракция двумерного пространства 8x8, отвечает только за топологию (кто где находится), инициализирует себя начальным набором случайных элементов, так же
обеспечивает безопасную перестановкудвух элементов по заданным координатам и предоставляет доступ к элементам по координатам для чтения.
Выполняет удаление элементов по запросу и реализует гравитацию — сдвигает оставшиеся элементы вниз и генерирует новые на пустые места.
3. MatchDetector
Вычислительный модуль, инкапсулирует логику поиска совпадений. Принимает текущее состояние Grid, сканирует и определяет, кто участвует в комбинациях.
Распознает сложные фигуры (4-в-ряд, крестовины) для того, чтобы сообщить системе о необходимости создать бонусный Token.
Проверяет, остались ли на поле потенциальные ходы.
4. ScoreKeeper
Модуль учета достижений игрока, слушает события уничтожения элементов и начисляет очки в зависимости от размера и сложности комбинации.
Ведет счетчик сделанных ходов и формирует итоговую статистику для вывода.
5. PlayerCommand
Абстракция действия, принимает «сырой» ввод, валидирует корректность, инкапсулирует данные о валидном ходе для передачи в ядро игры.
6. GameSession
Оркестратор, связывает независимые модули воедино, запускает цикл обработки одного хода: берет валидную PlayerCommand, просит Grid поменять фишки местами.
Управляет «каскадом»: опрашивает MatchDetector на наличие линий. Если линии есть -> передает данные в ScoreKeeper -> дает команду Grid на удаление и падение фишек -> снова опрашивает MatchDetector.
Возвращает ход назад (через Grid), если перестановка не привела к совпадению.
7. ConsoleConsole
Изолированный слой представления, должен отрисововывать поле в консоль в понятном виде, так же выводить сообщения об ошибках и текущий счет, захватывает нажатия клавиш или 
строковый ввод игрока и передает их дальше.
*/
