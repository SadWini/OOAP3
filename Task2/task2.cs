1) Определение границ системы:
Включено: Базовая пошаговая механика игры на поле 8x8. Генерация 5 типов элементов. Падение элементов вниз и распознавание прямых линий и сложных фигур с генерацией бонусов. 
Интерактивный консольный интерфейс ввода (через координаты) и вывода (отрисовка доски). Система подсчета очков и комбо.
Не включено: GUI, анимации и звуковые эффекты. Таймер реального времени, мультиплеер и таблица рекордов на сервере. Система сохранения/загрузки прогресса в файл.
2) Подсистемы вижу такие:
Пространственно-физическая подсистема: отвечает за хранение элементов, их координаты, перемещение и гравитацию (соответствует АТД Grid, Token).
Подсистема игровой логики и правил: отвечает за распознавание паттернов, генерацию бонусов и определение конца игры (соответствует АТД MatchDetector).
Аналитическая подсистема: отвечает за учет достижений и историю ходов (соответствует АТД ScoreKeeper).
Подсистема ввода-вывода: отвечает за трансляцию намерений человека в термины системы и визуализацию состояния мира (соответствует АТД PlayerCommand, ConsoleView).
3) "Метафоры":
Доска (Board) — замкнутое пространство 8x8, где происходит игра.
Фишка (Кристалл / Token) — базовый элемент одного из 5 типов.
Бомба / Бонус — особый вид фишки, уничтожающий больше элементов.
Схлопывание (Match) — процесс уничтожения совпавших линий.
Каскад (Цепная реакция) — ситуация, когда упавшие после "схлопывания" фишки образуют новые линии.
Гравитация — автоматическое смещение фишек в нижние пустые ячейки.
4) Функциональность:
Первичная генерация доски (без готовых совпадений?).
Валидация пользовательского ввода.
Обмен фишек местами. Откат обмена, если не образовалось линии 3-в-ряд.
Удаление линий, начисление очков с учетом множителей за каскад.
Смещение фишек вниз и генерация новых сверху.
Проверка наличия доступных ходов на доске.
5) Библиотеки:
Будем использовать стандартные методы языка без дополнительных игровых фреймворков.
Выделим для потенциального использования 2D_BoardEngine, стараясь, чтобы можно было это использовать для написания других клеточных игр, например, сапера.
